/**
 * Bundle the siesta XS worker scripts for the `siesta-xs-worker` binary
 * (rust/siesta-xs-worker), and satisfy the xsnap crate's generated-file
 * build inputs.
 *
 * Produces:
 *   packages/siesta/dist-xs/boot.js        — pre-bundle boot script (a
 *     copy of xsnap's committed polyfills: TextEncoder/TextDecoder plus
 *     freeze-based harden and assert shims)
 *   packages/siesta/dist-xs/worker-xs.js   — bundle of src/worker-xs.js
 *     (worker shell + CapTP wired to the siestaSend host function)
 *   rust/endo/xsnap/src/{ses_boot,worker_bootstrap,daemon_bootstrap}.js —
 *     stubs, written ONLY if absent: they satisfy xsnap's include_str!
 *     so the crate compiles; siesta-xs-worker never evaluates them. The
 *     real ones belong to the endor daemon's own bundler.
 *
 * Usage: node packages/siesta/scripts/bundle-xs-worker.mjs
 */
import '@endo/init';
import fs from 'fs';
import url from 'url';
import crypto from 'crypto';
import path from 'path';
import { makeBundle } from '@endo/compartment-mapper/bundle.js';
import { makeReadPowers } from '@endo/compartment-mapper/node-powers.js';

const readPowers = makeReadPowers({ fs, url, crypto, path });
const dirname = path.dirname(url.fileURLToPath(import.meta.url));
const distDir = path.resolve(dirname, '../dist-xs');
const xsnapSrcDir = path.resolve(dirname, '../../../rust/endo/xsnap/src');
fs.mkdirSync(distDir, { recursive: true });

// Node-only packages that must not enter an XS bundle. Mirrors the
// exclusion convention of bundle-bus-daemon-rust-xs.mjs.
const EXCLUDED_PACKAGES = new Set(['ses', '@endo/init', '@endo/lockdown']);

const packageDependenciesHook = ({ canonicalName, dependencies }) => {
  const filtered = new Set(
    [...dependencies].filter(dep => !EXCLUDED_PACKAGES.has(dep)),
  );
  if (filtered.size !== dependencies.size) {
    const removed = [...dependencies].filter(d => !filtered.has(d));
    console.log(
      `  ${canonicalName}: excluded ${removed.length} dep(s): ${removed.join(', ')}`,
    );
  }
  return { dependencies: filtered };
};

// --- Boot script: xsnap's committed polyfills, then lockdown ---
// XS implements Hardened JavaScript natively: siesta-xs-worker
// registers the engine's own `harden` and `lockdown` as globals
// (mxLockdown), so the polyfills' freeze-based harden shim steps
// aside (`if (!globalThis.harden)`) and the boot script ends by
// freezing the shared intrinsics. The ses shim is neither needed nor
// usable here (its repairIntrinsics fails on XS).
const polyfillsPath = path.join(xsnapSrcDir, 'polyfills.js');
const bootScript = `${fs.readFileSync(polyfillsPath, 'utf8')}
// XS native Hardened JavaScript: freeze the shared intrinsics so
// guest compartments cannot communicate or interfere through them.
lockdown();
`;
const bootDist = path.join(distDir, 'boot.js');
fs.writeFileSync(bootDist, bootScript);
console.log(`Wrote ${bootDist} (${bootScript.length} bytes)`);

// --- Worker shell bundle ---
const workerUrl = url.pathToFileURL(
  path.resolve(dirname, '../src/worker-xs.js'),
).href;
const workerBundle = await makeBundle(readPowers, workerUrl, {
  packageDependenciesHook,
});
const workerDist = path.join(distDir, 'worker-xs.js');
fs.writeFileSync(workerDist, workerBundle);
console.log(`Wrote ${workerDist} (${workerBundle.length} bytes)`);

// --- Stubs for xsnap's other include_str! inputs, if absent ---
for (const stub of [
  'ses_boot.js',
  'worker_bootstrap.js',
  'daemon_bootstrap.js',
]) {
  const stubPath = path.join(xsnapSrcDir, stub);
  if (!fs.existsSync(stubPath)) {
    fs.writeFileSync(
      stubPath,
      `/* Stub generated by packages/siesta/scripts/bundle-xs-worker.mjs so
 * the xsnap crate compiles. siesta-xs-worker never evaluates this file.
 * The real bundle is produced by the endor daemon's bundler. */
throw new Error('stub bootstrap: regenerate with the endor bundler');
`,
    );
    console.log(`Wrote stub ${stubPath}`);
  }
}
